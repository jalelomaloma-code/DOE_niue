                'document_category_id' => $categories[$data['category']] ?? null,
                'published_date' => now()->subDays(15 - $index)->toDateString(),
                'is_featured' => $data['featured'],
                'status' => ContentStatus::Published,
                'published_at' => now()->subDays(15 - $index),
                'is_demo' => true,
            ]);

            $pdfPath = DemoPdfGenerator::make($data['title'], $data['category'], $data['body']);

