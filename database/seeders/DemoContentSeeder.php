/**
 * Populates every content table with realistic, clearly-marked placeholder
 * content so the homepage (and the admin panel) look credible for a client
 * review before real Department content lands.
 *
 * Every record this seeder creates carries `is_demo = true` and is removed,
 * media included, by `php artisan demo:purge`.
 *
 * Imagery is generated at seed time by DemoImageGenerator (palette gradients
 * from GD, labelled "DEMO — <subject>") rather than sourced photography —
 * see docs/superpowers/specs/2026-08-07-foundation-homepage-design.md §6 for
 * why. Document files are generated by DemoPdfGenerator for the same reason:
 * zero licensing risk, the seeder runs fully offline, and a placeholder that
 * survives into production is obvious on sight.
 */
class DemoContentSeeder extends Seeder
{
    public function run(): void
    {
        $programmes = $this->seedProgrammes();
        $this->seedNewsArticles();
        $this->seedProjects($programmes);
        $this->seedDocuments();
    }

