    private function attachFeaturedImage(Programme|Project|NewsArticle $model, string $palette, string $subject): void
    {
        $imagePath = DemoImageGenerator::make($palette, "DEMO — {$subject}", 1920, 900);

        $model->addMedia($imagePath)
            ->preservingOriginal()
            ->withCustomProperties(['alt' => "Placeholder image representing {$subject} (demo content)"])
            ->toMediaCollection('featured_image');
    }
